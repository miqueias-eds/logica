var diaDaSemana = "Quarta"

switch (diaDaSemana) {
    case "Segunda":
        console.log("Feijão com arroz")
        break;
    case "Terça":
        console.log("Cuscuz com ovo")
        break;
    case "Quarta":
        console.log("Buchada de bode")
        break;
    case "Quinta":
        console.log("Vaca atolada")
        break;
    case "Sexta":
        console.log("Sarapatel")
        break;
    case "Sábado":
        console.log("Pirão")
        break;
    case "Domingo":
        console.log("Baião de dois")
        break;
}